package sqlbuilder

import (
	"errors"
	"fmt"
	"reflect"
)

var (
	// ErrInsertRowExceedsPlaceholderLimit is returned by Struct#InsertIntoBatches
	// and its variants when a single record alone needs more placeholders than
	// the limit allows. The concrete error is *InsertRowExceedsPlaceholderLimitError.
	ErrInsertRowExceedsPlaceholderLimit = errors.New("go-sqlbuilder: record exceeds insert placeholder limit")
)

// InsertRowExceedsPlaceholderLimitError reports a record that cannot be inserted
// within the placeholder limit passed to Struct#InsertIntoBatches.
//
// It identifies the record by its index in the value list passed to the method,
// which makes it possible to locate the offending record even when other items
// in the list are not of the expected struct type.
type InsertRowExceedsPlaceholderLimitError struct {
	// Index is the position of the record in the value list passed to
	// Struct#InsertIntoBatches.
	Index int

	// Placeholders is the number of placeholders needed to insert the record alone.
	Placeholders int

	// Limit is the limit passed to Struct#InsertIntoBatches.
	Limit int
}

// Error implements error.
func (e *InsertRowExceedsPlaceholderLimitError) Error() string {
	return fmt.Sprintf("go-sqlbuilder: record at index %d needs %d placeholders, exceeding the limit %d", e.Index, e.Placeholders, e.Limit)
}

// Unwrap returns ErrInsertRowExceedsPlaceholderLimit.
func (e *InsertRowExceedsPlaceholderLimitError) Unwrap() error {
	return ErrInsertRowExceedsPlaceholderLimit
}

// InsertBatch is a single INSERT statement generated by Struct#InsertIntoBatches.
//
// Records in a batch keep the same order as they appear in the value list passed
// to Struct#InsertIntoBatches, and Indices records where they came from.
type InsertBatch struct {
	*InsertBuilder

	// Indices lists positions, in the original value list, of the records inserted
	// by this batch. Its order and length match the VALUES clauses built by
	// the embedded InsertBuilder.
	Indices []int
}

// InsertIntoBatches creates a list of `InsertBuilder`s using verb INSERT INTO,
// splitting records into batches that each use no more than maxPlaceholders
// placeholders.
//
// Unlike InsertInto, which puts every record into a single statement, this method
// keeps each generated statement within the placeholder limit imposed by many
// database drivers. Batches are formed from the number of columns actually
// written for their records, so records that omit optional fields are accounted
// for correctly.
//
// Records are kept in their original order. For every generated batch, Indices
// maps each row of the statement back to its position in value. Batches without
// any record are not generated.
//
// Items in value whose type is not the struct type are ignored, as in InsertInto.
// If maxPlaceholders is not positive, no limit is applied and all records are
// placed in a single statement.
//
// If a single record needs more placeholders than maxPlaceholders, the method
// returns an *InsertRowExceedsPlaceholderLimitError identifying the record.
func (s *Struct) InsertIntoBatches(table string, maxPlaceholders int, value ...interface{}) ([]*InsertBatch, error) {
	return s.insertIntoBatches(s.withTags, s.withoutTags, maxPlaceholders, value, func() *InsertBuilder {
		ib := s.Flavor.NewInsertBuilder()
		ib.InsertInto(table)
		return ib
	})
}

// InsertIgnoreIntoBatches creates a list of `InsertBuilder`s using verb INSERT IGNORE INTO,
// splitting records into batches that each use no more than maxPlaceholders placeholders.
//
// See InsertIntoBatches for details about batching and error handling.
func (s *Struct) InsertIgnoreIntoBatches(table string, maxPlaceholders int, value ...interface{}) ([]*InsertBatch, error) {
	return s.insertIntoBatches(s.withTags, s.withoutTags, maxPlaceholders, value, func() *InsertBuilder {
		ib := s.Flavor.NewInsertBuilder()
		ib.InsertIgnoreInto(table)
		return ib
	})
}

// ReplaceIntoBatches creates a list of `InsertBuilder`s using verb REPLACE INTO,
// splitting records into batches that each use no more than maxPlaceholders placeholders.
//
// See InsertIntoBatches for details about batching and error handling.
func (s *Struct) ReplaceIntoBatches(table string, maxPlaceholders int, value ...interface{}) ([]*InsertBatch, error) {
	return s.insertIntoBatches(s.withTags, s.withoutTags, maxPlaceholders, value, func() *InsertBuilder {
		ib := s.Flavor.NewInsertBuilder()
		ib.ReplaceInto(table)
		return ib
	})
}

// structInsertRow is a value whose type matches the Struct, together with its
// index in the value list passed to a Struct insert method.
type structInsertRow struct {
	index int
	value reflect.Value
}

// structInsertCell is the value bound for one struct field of one record.
type structInsertCell struct {
	value interface{}

	// nilForColumn reports that this cell does not contribute a value for its
	// column. If every record in a statement reports true for the same column,
	// the column is omitted from the statement.
	nilForColumn bool
}

// insertIntoBatches implements the batched insert methods.
func (s *Struct) insertIntoBatches(with, without []string, maxPlaceholders int, value []interface{}, newBuilder func() *InsertBuilder) ([]*InsertBatch, error) {
	tagged := s.structFieldsParser().FilterTags(with, without)

	if tagged == nil {
		return nil, nil
	}

	rows := s.collectInsertRows(value)

	if len(rows) == 0 {
		return nil, nil
	}

	fields := tagged.ForInsert
	cells := s.insertRowCells(fields, with, rows)

	batchOf := func(start, end int) *InsertBatch {
		// A batch with no writable column has nothing to bind. It is not turned
		// into a statement, so empty batches never produce write SQL.
		return s.newInsertBatch(newBuilder(), fields, rows[start:end], cells[start:end])
	}

	batches := make([]*InsertBatch, 0, 1)

	if maxPlaceholders <= 0 {
		if batch := batchOf(0, len(rows)); batch != nil {
			batches = append(batches, batch)
		}

		return batches, nil
	}

	// nonNil[j] counts records in the pending batch that bind a value for field j.
	nonNil := make([]int, len(fields))
	start := 0

	for i := range rows {
		// The batch would consist of rows[start:i+1]. Its column count is the
		// number of fields bound by at least one of those records.
		effective := 0

		for j := range fields {
			if !cells[i][j].nilForColumn || nonNil[j] > 0 {
				effective++
			}
		}

		if (i-start+1)*effective <= maxPlaceholders {
			for j := range fields {
				if !cells[i][j].nilForColumn {
					nonNil[j]++
				}
			}

			continue
		}

		// The record doesn't fit. Emit the pending batch before it.
		if i > start {
			if batch := batchOf(start, i); batch != nil {
				batches = append(batches, batch)
			}

			for j := range nonNil {
				nonNil[j] = 0
			}

			start = i

			effective = 0

			for j := range fields {
				if !cells[i][j].nilForColumn {
					effective++
				}
			}
		}

		// A batch holding only this record still exceeds the limit.
		if effective > maxPlaceholders {
			return nil, &InsertRowExceedsPlaceholderLimitError{
				Index:        rows[i].index,
				Placeholders: effective,
				Limit:        maxPlaceholders,
			}
		}

		for j := range fields {
			if !cells[i][j].nilForColumn {
				nonNil[j]++
			}
		}
	}

	if start < len(rows) {
		if batch := batchOf(start, len(rows)); batch != nil {
			batches = append(batches, batch)
		}
	}

	return batches, nil
}

// collectInsertRows returns records in value whose type matches s, preserving
// their order and original indices.
func (s *Struct) collectInsertRows(value []interface{}) []structInsertRow {
	rows := make([]structInsertRow, 0, len(value))

	for i, item := range value {
		v := reflect.ValueOf(item)
		v = dereferencedFieldValue(v)

		if !v.IsValid() || v.Type() != s.structType {
			continue
		}

		rows = append(rows, structInsertRow{
			index: i,
			value: v,
		})
	}

	return rows
}

// insertRowCells extracts the value bound for every field of every record.
func (s *Struct) insertRowCells(fields []*structField, with []string, rows []structInsertRow) [][]structInsertCell {
	cells := make([][]structInsertCell, len(rows))

	for i, row := range rows {
		rowCells := make([]structInsertCell, len(fields))

		for j, sf := range fields {
			val, ok := fieldByIndex(row.value, sf.Index, false)

			if !ok || !val.IsValid() {
				rowCells[j].nilForColumn = true
				continue
			}

			if isEmptyValue(val) && sf.ShouldOmitEmpty(with...) {
				// The column may be dropped if every record omits it. When the
				// column is kept, the zero value is still bound.
				rowCells[j].nilForColumn = true
			}

			val = dereferencedFieldValue(val)

			if val.IsValid() {
				rowCells[j].value = val.Interface()
			}
		}

		cells[i] = rowCells
	}

	return cells
}

// buildInsertData returns the columns written by rows and the values bound by
// each row. A column is included only if at least one row binds a value for it.
func (s *Struct) buildInsertData(fields []*structField, rows []structInsertRow, cells [][]structInsertCell) (cols []string, values [][]interface{}) {
	cols = make([]string, 0, len(fields))
	values = make([][]interface{}, len(rows))

	for j, sf := range fields {
		used := false

		for i := range rows {
			if !cells[i][j].nilForColumn {
				used = true
				break
			}
		}

		if !used {
			continue
		}

		cols = append(cols, sf.Quote(s.Flavor))

		for i := range rows {
			values[i] = append(values[i], cells[i][j].value)
		}
	}

	return cols, values
}

// newInsertBatch fills ib with the columns and values of rows and wraps it into
// an InsertBatch. It returns nil if no row binds a value for any column, in
// which case there is no meaningful statement to execute.
func (s *Struct) newInsertBatch(ib *InsertBuilder, fields []*structField, rows []structInsertRow, cells [][]structInsertCell) *InsertBatch {
	cols, values := s.buildInsertData(fields, rows, cells)

	if len(cols) == 0 {
		return nil
	}

	ib.Cols(cols...)

	for _, v := range values {
		ib.Values(v...)
	}

	indices := make([]int, len(rows))

	for i, row := range rows {
		indices[i] = row.index
	}

	return &InsertBatch{
		InsertBuilder: ib,
		Indices:       indices,
	}
}
